/**
 * Helper function to find which Kuli a surname belongs to,
 * along with its Wadhe Bhau (brother surnames in the same Kuli).
 */
export function findWadheBhauBySurname(surname: string) {
  if (!surname || surname.trim() === '') return null;
  const cleanSurname = surname.trim().toLowerCase();

  for (const kuli of VANJARI_KULI_LIST) {
    const match = kuli.surnames.some(s => s.toLowerCase().includes(cleanSurname) || cleanSurname.includes(s.toLowerCase()));
    if (match) {
      return {
        kuli,
        wadheBhauSurnames: kuli.surnames.filter(s => !s.toLowerCase().includes(cleanSurname))
      };
    }
  }
  return null;
}
